#!/usr/bin/env python3
"""Renders the mod manager's font into src/platform/vita/menufont.h.

ASCII 32-126 from DejaVu Sans Mono Bold, one 4-bit alpha cell per glyph in a
16-column atlas. The manager runs before the game has loaded any of its own
art, so it cannot use fontus.tim.

usage: make_menu_font.py [path to DejaVuSansMono-Bold.ttf] > menufont.h
"""
import sys
from PIL import Image, ImageDraw, ImageFont

ttf = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/fonts/truetype/dejavu/DejaVuSansMono-Bold.ttf"
CW, CH, SIZE = 12, 22, 19
font = ImageFont.truetype(ttf, SIZE)
cols, rows = 16, 6
atlas = Image.new("L", (cols * CW, rows * CH), 0)
d = ImageDraw.Draw(atlas)
asc, desc = font.getmetrics()
for i, c in enumerate(range(32, 127)):
    x, y = (i % cols) * CW, (i // cols) * CH
    w = d.textlength(chr(c), font=font)
    d.text((x + (CW - w) / 2, y + (CH - asc - desc) / 2), chr(c), font=font, fill=255)
px = atlas.tobytes()
packed = bytes(((px[i] >> 4) | (px[i + 1] & 0xF0)) for i in range(0, len(px), 2))

print("// menufont.h - generated by tools/vita/make_menu_font.py, do not edit.")
print("//")
print("// Glyphs from DejaVu Sans Mono Bold. DejaVu fonts are (c) Bitstream, Inc.")
print("// (Bitstream Vera) and the DejaVu changes are in the public domain; the")
print("// Bitstream Vera license allows embedding and redistribution with this notice.")
print("#pragma once")
print("#define MENUFONT_CELL_W %d" % CW)
print("#define MENUFONT_CELL_H %d" % CH)
print("#define MENUFONT_COLS   %d" % cols)
print("#define MENUFONT_ROWS   %d" % rows)
print("// 4-bit alpha, two pixels a byte, low nibble first, row-major.")
print("static const unsigned char kMenuFont[%d] = {" % len(packed))
for i in range(0, len(packed), 24):
    print("    " + ", ".join("0x%02X" % b for b in packed[i:i + 24]) + ",")
print("};")
